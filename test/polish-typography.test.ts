import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { DESIGN_TOKENS, TOKENS_FILE } from '../server/design-tokens.ts';
import { readTokensStatus, saveTokens } from '../server/tokens-file.ts';
import { savePayload, tokenLayer } from '../web/src/polish/draft.ts';

test('independent typography previews survive saving and refreshing a legacy Vite page without losing imports', async t => {
 const dir = await mkdtemp(join(tmpdir(), 'typography-'));
 t.after(() => rm(dir, { recursive: true, force: true }));
 await mkdir(join(dir, 'src'));
 const imports = ['https://example.com/original-font.css', 'https://example.com/layout.css'];
 const values = Object.fromEntries(DESIGN_TOKENS.filter(x => x.name !== '--sui-font-ui').map(x => [x.name, x.group === 'font' ? (x.name.includes('size') ? '16px' : 'sans-serif') : '0']));
 await writeFile(join(dir, TOKENS_FILE), imports.map(x => `@import url("${x}");`).join('\n') + '\n:root {\n' + Object.entries(values).map(([k,v]) => `${k}: ${v};`).join('\n') + '\n}');
 await writeFile(join(dir, 'index.html'), '<link rel="stylesheet" href="/src/design-tokens.css"><style>body{font-family:var(--sui-font-sans)}h1{font-family:var(--sui-font-heading)}button,input{font-family:inherit}</style><h1>真实标题 Real heading</h1><p>真实正文 Real body</p><button><span>立即开始 Start</span></button><input value="真实输入"><code>code untouched</code>');
 const server = await createServer({ root: dir, configFile: false, server: { port: 0 } });
 await server.listen(); t.after(() => server.close());
 const browser = await chromium.launch({ headless: true }); t.after(() => browser.close());
 const page = await browser.newPage();
 await page.route('https://example.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }));
 await page.goto(server.resolvedUrls!.local[0]!);
 const status = await readTokensStatus(dir);
 assert.equal(status.organized, true, '17-token projects remain organized');
 const tokens = { '--sui-font-heading': 'serif', '--sui-font-sans': 'monospace', '--sui-font-ui': 'cursive' } as const;
 await page.addStyleTag({ content: tokenLayer(tokens) });
 const families = () => page.evaluate(() => ['h1','p','button','input'].map(s => getComputedStyle(document.querySelector(s)!).fontFamily));
 assert.deepEqual(await families(), ['serif','monospace','cursive','cursive'], 'preview respects all three independent roles');
 const payload = savePayload({ tokens, fontImports: ['https://example.com/new-font.css'] }, status);
 const updated = new Promise<void>(resolve => server.watcher.once("change", () => resolve()));
 await saveTokens(dir, payload.values, payload.fontImports);
 await updated;
 await page.reload();
 assert.deepEqual(await families(), ['serif','monospace','cursive','cursive'], 'saved typography survives reload');
 const saved = await readTokensStatus(dir);
 assert.deepEqual(saved.fontImports, [...imports, 'https://example.com/new-font.css']);
 assert.equal(saved.values['--sui-font-ui'], 'cursive');
 const reset = new Promise<void>(resolve => server.watcher.once('change', () => resolve()));
 await saveTokens(dir, { '--sui-font-ui': 'var(--sui-font-sans)' });
 await reset;
 await page.reload();
 assert.deepEqual(await families(), ['serif','monospace','monospace','monospace'], 'controls can follow body again');
 assert.equal((await readFile(join(dir,TOKENS_FILE),'utf8')).includes('https://example.com/layout.css'), true);
});

test('font selection preserves existing relative imports and only rejects new unsafe imports', async t => {
 const dir = await mkdtemp(join(tmpdir(), 'typography-imports-'));
 t.after(() => rm(dir, { recursive: true, force: true }));
 await mkdir(join(dir, 'src'));
 const original = '@import url("./icons.css");\n@import "./layout.css";\n:root {\n' + DESIGN_TOKENS.filter(x => x.name !== '--sui-font-ui').map(x => `${x.name}: initial;`).join('\n') + '\n}';
 await writeFile(join(dir, TOKENS_FILE), original);
 const status = await readTokensStatus(dir);
 const payload = savePayload({ tokens: { '--sui-font-heading': 'serif' }, fontImports: ['https://example.com/new-font.css'] }, status);
 await saveTokens(dir, payload.values, payload.fontImports);
 const saved = await readFile(join(dir, TOKENS_FILE), 'utf8');
 assert.ok(saved.includes('@import url("./icons.css");'));
 assert.ok(saved.includes('@import "./layout.css";'));
 await assert.rejects(saveTokens(dir, {}, ['./new-unsafe.css']));
 assert.equal(await readFile(join(dir, TOKENS_FILE), 'utf8'), saved);
});
